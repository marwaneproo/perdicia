import { AlertTriangle, CheckCircle2, Info, Lightbulb } from 'lucide-react'
import NoDataset from '../components/NoDataset'
import { ErrorState, Loading } from '../components/States'
import { useAsync } from '../hooks/useAsync'
import { useDataset } from '../hooks/useDataset'
import { api } from '../services/api'
import type { Insight } from '../types'
import type { PageId } from '../layouts/AppLayout'

const ICON = { positive: CheckCircle2, warning: AlertTriangle, info: Info }
const TONE = { positive: 'text-emerald-600 bg-emerald-50', warning: 'text-amber-600 bg-amber-50', info: 'text-brand-600 bg-brand-50' }

function Section({ title, subtitle, items }: { title: string; subtitle: string; items: Insight[] }) {
  return (
    <section>
      <h2 className="text-base font-semibold text-slate-900">{title}</h2>
      <p className="mb-3 text-sm text-slate-500">{subtitle}</p>
      <div className="grid gap-3 md:grid-cols-2">
        {items.map((i, k) => {
          const Icon = i.type === 'recommendation' ? Lightbulb : ICON[i.severity]
          return (
            <div key={k} className="card flex gap-3 p-4">
              <div className={`h-fit rounded-lg p-2 ${TONE[i.severity]}`}><Icon className="h-4 w-4" /></div>
              <div><p className="text-sm font-semibold text-slate-900">{i.title}</p><p className="mt-0.5 text-sm text-slate-600">{i.text}</p></div>
            </div>
          )
        })}
      </div>
    </section>
  )
}

export default function Insights({ go }: { go: (p: PageId) => void }) {
  const { dataset } = useDataset()
  const { data, loading, error } = useAsync(() => (dataset ? api.insights(dataset.id) : Promise.resolve(null)), [dataset?.id])
  if (!dataset) return <NoDataset go={go} />
  if (loading) return <Loading label="Generating insights…" />
  if (error) return <ErrorState message={error} />
  if (!data) return null
  return (
    <div className="space-y-8">
      <p className="text-sm text-slate-500">Insights are generated by deterministic rules applied to your data — no external AI model is used.</p>
      <Section title="Calculated facts" subtitle="Computed directly from your dataset." items={data.filter(i => i.type === 'fact')} />
      <Section title="Recommendations" subtitle="Suggested actions derived from the facts above — to be validated by you." items={data.filter(i => i.type === 'recommendation')} />
    </div>
  )
}
